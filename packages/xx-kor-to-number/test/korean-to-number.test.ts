describe('입력 처리', function () {
  it('문자열이 아닌 입력은 String으로 바꿔 처리한다', function () {
    expect(koreanToNumber(12.5 as unknown as string)).toBe(12.5);
    expect(koreanToNumber(null as unknown as string)).toBeNaN();
    expect(koreanToNumber(undefined as unknown as string)).toBeNaN();
  });

  it('숫자로 읽을 글자가 없으면 NaN이다', function () {
    eq('', NaN);
    eq('abc', NaN);
    eq('-', NaN);
    eq('만만', NaN);
  });

  it('숫자로 읽을 수 없는 글자는 버리고 남은 글자만 읽는다', function () {
    // 이(2)와 구(9)만 남는다. NaN을 돌려주지 않는다.
    eq('이목구비', 29);
    eq('1e3', 13);
    eq('1,2,3', 123);
    eq('0.5.5', 0.55);
  });

  it('해까지만 단위로 읽고, 자와 양은 단위로 읽지 않는다', function () {
    eq('해', 1e20);
    eq('1해', 1e20);
    // 자와 양은 버려져 앞의 숫자만 남는다.
    eq('1자', 1);
    eq('1양', 1);
  });
});
