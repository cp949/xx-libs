// 한글 숫자 변환의 현재 동작을 고정하는 테스트.
// 케이스 상당수는 dragonteros/kor-to-number.js의 테스트에서 가져왔다(THIRD-PARTY-NOTICES.md).
// 어색해 보이는 결과(예: '10일'이 101)도 원본 동작이므로 바꾸지 않고 고정한다.
import { describe, expect, it } from 'vitest';
import { koreanToNumber } from '../src/index.js';

function eq(original: string, expected: number) {
  if (Number.isNaN(expected)) {
    expect(koreanToNumber(original), `TEST='${original}' expected = NaN`).toBeNaN();
  } else {
    expect(koreanToNumber(original), `TEST='${original}' expected = ${expected}`).toBe(expected);
  }
}

function neq(original: string, expected: number) {
  expect(koreanToNumber(original), `TEST='${original}' expected != ${expected}`).not.toBe(expected);
}

describe('숫자만', function () {
  it('쉼표 없이', function () {
    eq('0', 0);
    eq('1', 1);
    eq('10', 10);
    eq('100', 100);
    eq('1000', 1000);
    eq('10000', 10000);
    eq('123', 123);
    eq('12345', 12345);
    eq('2147483648', 2147483648);
  });

  it('쉼표', function () {
    eq('1,000', 1000);
    eq('10,000', 10000);
    eq('12,345', 12345);
    eq('2,147,483,648', 2147483648);
  });

  it('단위', function () {
    eq('0개', 0);
    eq('1층', 1);
    eq('10시', 10);
    eq('100불', 100);
    eq('1,000 km', 1000);
    eq('10,000원', 10000);
    eq('123 가지', 123);
    eq('12345대', 12345);
  });
});

